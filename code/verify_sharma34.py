# 完整 CIEDE2000 单点函数（与 assign_ce_full_njit 算法一致）
def deltaE_full(lab1, lab2):
    L1,a1,b1 = lab1; L2,a2,b2 = lab2
    C1 = (a1*a1+b1*b1)**0.5; C2 = (a2*a2+b2*b2)**0.5
    mC = (C1+C2)/2.0
    G = 0.5*(1.0-(mC**7/(mC**7+25.0**7))**0.5)
    a1p = (1+G)*a1; a2p = (1+G)*a2
    C1p = (a1p*a1p+b1*b1)**0.5; C2p = (a2p*a2p+b2*b2)**0.5
    h1p = np.degrees(np.arctan2(b1,a1p))%360.0; h2p = np.degrees(np.arctan2(b2,a2p))%360.0
    dLp = L2-L1; dCp = C2p-C1p; mL = (L1+L2)/2.0; mCp = (C1p+C2p)/2.0
    hd = h2p-h1p; ah = (h1p+h2p)/2.0
    if abs(hd) > 180.0: ah += 180.0
    if ah < 0: ah += 360.0
    elif ah >= 360.0: ah -= 360.0
    if C1p*C2p == 0.0: ah = h1p+h2p
    dh = hd
    if dh > 180.0: dh -= 360.0
    elif dh < -180.0: dh += 360.0
    if C1p*C2p == 0.0: dh = 0.0
    dHp = 2.0*(C1p*C2p)**0.5*np.sin(np.radians(dh)/2.0)
    SL = 1.0+0.015*(mL-50.0)**2/(20.0+(mL-50.0)**2)**0.5
    SC = 1.0+0.045*mCp
    T = (1.0-0.17*np.cos(np.radians(ah-30.0))+0.24*np.cos(np.radians(2*ah))
         +0.32*np.cos(np.radians(3*ah+6.0))-0.20*np.cos(np.radians(4*ah-63.0)))
    SH = 1.0+0.015*mCp*T
    dtheta = 30.0*np.exp(-((ah-275.0)/25.0)**2)
    RC = 2.0*(mCp**7/(mCp**7+25.0**7))**0.5
    RT = -np.sin(np.radians(2*dtheta))*RC
    d2 = (dLp/SL)**2 + (dCp/SC)**2 + (dHp/SH)**2 + RT*(dCp/SC)*(dHp/SH)
    return max(d2,0)**0.5

